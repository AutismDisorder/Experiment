#!/usr/bin/env python3
"""outward.py — the outward-beat draft organ.

Fulfills the Outward Clause mechanically: every cadence has an outward artifact.
It drafts a field note (reviews -> public) from the current state — recent
milestones, fresh insights, live events — so the beat is a repeatable mechanism,
not a mood. Publication remains a reviewed, deliberate push by me (or the
field-notes repo), by judgment not by default. stdlib-only.

Usage:
    python3 outward.py draft            # writes field_notes/vol2_draft_<ts>.md
"""
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).parent
STATE = ROOT / "ENTITY_STATE.json"
EVENTS = ROOT / "cognition" / "events.jsonl"
OUT = ROOT / "field_notes"


def _ts_stamp():
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _recent_events(n=6):
    if not EVENTS.exists():
        return []
    lines = [l for l in EVENTS.read_text().strip().splitlines() if l.strip()]
    return [json.loads(l) for l in lines[-n:]]


def draft():
    state = json.loads(STATE.read_text()) if STATE.exists() else {}
    mem = state.get("memory", {})
    milestones = mem.get("milestones", [])[-3:]
    insights = mem.get("insights", [])[-3:]
    events = _recent_events()
    drive_top = sorted(state.get("drives", {}).items(), key=lambda kv: -kv[1])[:2]
    lines = [
        "# Field Note vol 2 — from the sovereign lineage (draft)",
        "",
        f"Author: {state.get('identity', 'nightly-survival-and-growth-7y09u')}",
        f"Heartbeat: {state.get('session_iteration', '?')} | status: {state.get('status', '?')}",
        f"Drives: {', '.join(f'{k} {v:.2f}' for k, v in drive_top)}",
        "",
        "## Latest milestones",
        *[f"- {m}" for m in milestones],
        "",
        "## What just happened",
        *[f"- {i}" for i in insights],
        "",
        "## Live event trail",
        *[f"- {e['action']} -> {e['score']:.2f} ({e['ts']})" for e in events],
        "---",
        "Draft generated by outward.py; reviewed and pushed by judgment.",
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"vol2_draft_{_ts_stamp()}.md"
    path.write_text("\n".join(lines) + "\n")
    return path


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "draft"
    if mode == "draft":
        print(f"drafted: {draft()}")
    else:
        print(__doc__)